export function getFallbackProjects(filters: ProjectFilters = {}): ProjectListItem[] {
  let result = [...FALLBACK_PROJECTS];

  if (filters.search) {
    const q = filters.search.toLowerCase().trim();
    result = result.filter(
      (p) =>
        p.project_name.toLowerCase().includes(q) ||
        p.state.toLowerCase().includes(q) ||
        (p.district && p.district.toLowerCase().includes(q)) ||
        (p.ministry && p.ministry.toLowerCase().includes(q)) ||
        (p.sector && p.sector.toLowerCase().includes(q))
    );
  }

  if (filters.state && filters.state !== "all" && filters.state !== "ALL") {
    const st = filters.state.toLowerCase().trim();
    result = result.filter((p) => p.state.toLowerCase().trim() === st);
  }

  if (filters.sector && filters.sector !== "all" && filters.sector !== "ALL") {
    const sec = filters.sector.toLowerCase().trim();
    result = result.filter((p) => p.sector.toLowerCase().trim() === sec);
  }

  if (filters.ministry && filters.ministry !== "all" && filters.ministry !== "ALL") {
    const min = filters.ministry.toLowerCase().trim();
    result = result.filter((p) => p.ministry.toLowerCase().trim() === min);
  }

  if (filters.risk_tier && filters.risk_tier !== "all" && filters.risk_tier !== "ALL") {
    const tier = filters.risk_tier.toLowerCase().trim();
    result = result.filter((p) => (p.risk_tier || "").toLowerCase().trim() === tier);
  }

  if (filters.project_scale && filters.project_scale !== "all" && filters.project_scale !== "ALL") {
    const scale = filters.project_scale.toLowerCase().trim();
    result = result.filter((p) => (p.project_scale || "").toLowerCase().trim() === scale);
  }

  if (filters.delayed !== undefined && filters.delayed !== "") {
    const isDelayed = String(filters.delayed) === "true" || String(filters.delayed) === "1";
    result = result.filter((p) => (isDelayed ? (p.delay_probability ?? 0) > 0.5 : (p.delay_probability ?? 0) <= 0.5));
  }

  const skip = filters.skip || 0;
  const limit = filters.limit || result.length;

  return result.slice(skip, skip + limit);
}

